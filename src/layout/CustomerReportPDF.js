import PDFDocument from "pdfkit";

export const generateCustomerReportPDF = async (customers, reportTitle, generatedBy) => {
  const doc = new PDFDocument({ margin: 40, size: "A4" });

  doc.fontSize(20).text(reportTitle, { align: "center" });
  doc.moveDown(0.5);
  doc.fontSize(10)
     .text(`Generated by: ${generatedBy} | Date: ${new Date().toLocaleDateString()}`, { align: "center" });
  doc.moveDown(2);

  const headers = ["OR Number", "Registration Date"];
  const colWidths = [200, 200];
  let y = doc.y + 10;

  const drawRow = (row, y, isHeader = false) => {
    let x = 40;
    row.forEach((text, i) => {
      doc.fontSize(isHeader ? 10 : 9).text(text || "-", x, y, { width: colWidths[i] });
      x += colWidths[i];
    });
  };

  drawRow(headers, y, true);
  y += 20;

  customers.forEach((c) => {
    drawRow(
      [c.orNumber, c.createdAt ? new Date(c.createdAt).toLocaleDateString() : "-"],
      y
    );
    y += 20;
    if (y > 720) {
      doc.addPage();
      y = 40;
      drawRow(headers, y, true);
      y += 20;
    }
  });

  return doc;
};
