import PDFDocument from "pdfkit";
import { ChartJSNodeCanvas } from "chartjs-node-canvas";

export const generateMenuReportPDF = async (menuData, reportTitle, generatedBy) => {
  const doc = new PDFDocument({ margin: 40, size: "A4" });


  doc.fontSize(20).text(reportTitle, { align: "center" });
  doc.moveDown(0.5);
  doc.fontSize(10).text(
    `Generated by: ${generatedBy} | Date: ${new Date().toLocaleDateString()}`,
    { align: "center" }
  );

  doc.moveDown(5);

 
  const chartWidth = 400;  
  const chartHeight = 250; 
  const chartCanvas = new ChartJSNodeCanvas({ width: chartWidth, height: chartHeight });

  const labels = menuData.map(item => item.menuName || "-");
  const feedbackCounts = menuData.map(item => item.feedbackCount ?? 0);
  const avgRatings = menuData.map(item => (typeof item.avgRating === "number" ? item.avgRating : 0));

  const chartConfig = {
    type: "bar",
    data: {
      labels,
      datasets: [
        {
          label: "Feedback Count",
          data: feedbackCounts,
          backgroundColor: "#3b82f6",
        },
        {
          label: "Average Rating",
          data: avgRatings,
          backgroundColor: "#10b981",
        },
      ],
    },
    options: {
      responsive: false,
      plugins: {
        title: {
          display: true,
          text: "Menu Feedback Overview",
          font: { size: 16, weight: "bold" },
        },
        legend: { position: "bottom" },
      },
      scales: { y: { beginAtZero: true } },
    },
  };

  const chartBuffer = await chartCanvas.renderToBuffer(chartConfig);
  const chartX = (doc.page.width - chartWidth) / 2;
  const chartY = doc.y;
  doc.image(chartBuffer, chartX, chartY, { width: chartWidth, height: chartHeight });


  doc.moveDown(25);


  const headers = ["Menu Item", "Feedback Count", "Average Rating"];
  const colWidths = [300, 100, 100];
  let y = doc.y;

  const drawRow = (row, yPos, isHeader = false) => {
    let x = doc.page.margins.left;
    row.forEach((text, i) => {
      doc.fontSize(isHeader ? 10 : 9).text(String(text ?? "-"), x, yPos, {
        width: colWidths[i],
        ellipsis: true,
      });
      x += colWidths[i];
    });
  };

  drawRow(headers, y, true);
  y += 25;

  menuData.forEach(item => {
    const row = [
      item.menuName || "-",
      item.feedbackCount ?? 0,
      typeof item.avgRating === "number" ? item.avgRating.toFixed(2) : "0.00"
    ];
    drawRow(row, y);
    y += 25;

    if (y > doc.page.height - 60) {
      doc.addPage();
      y = doc.y;
      drawRow(headers, y, true);
      y += 25;
    }
  });

  return doc;
};
