import PDFDocument from "pdfkit";

export const generateFeedbackPDF = (data, reportTitle, generatedBy) => {
  const doc = new PDFDocument({ margin: 30, size: "A4" });


  doc.fontSize(16).text("Company Logo", 30, 30, { align: "left" });
  doc.fontSize(18).text(reportTitle, 0, 30, { align: "center" });
  doc.fontSize(12).text(`Generated by: ${generatedBy} | Generated on: ${new Date().toLocaleDateString()}`, 30, 60);
  doc.moveDown(2);


  doc.fontSize(14).text("Section 1: Summary Statistics", { underline: true });
  const summary = data.summary || {};
  const metrics = [
    ["Total Customers", summary.totalCustomers || "-"],
    ["Total Feedback Submitted", summary.totalFeedback || "-"],
    ["Average Overall Experience", summary.avgOverall || "-"],
    ["Average Food Quality", summary.avgFood || "-"],
    ["Average Service", summary.avgService || "-"],
    ["Feedback by Customer Type", summary.byCustomerType || "-"],
    ["Recommendations (Yes/Maybe/No)", summary.recommendations || "-"]
  ];
  metrics.forEach(([metric, value]) => doc.fontSize(12).text(`${metric}: ${value}`));
  doc.moveDown(1);

 
  doc.fontSize(14).text("Section 2: Feedback Details", { underline: true });
  const headers = ["OR Number","Customer Name","Customer Type","Menu Items","Overall Experience","Feedback Category","Feedback Message","Date"];
  const colWidths = [60, 100, 70, 100, 60, 80, 150, 60];

  const drawRow = (row, y, isHeader = false) => {
    let x = 30;
    row.forEach((text, i) => {
      const safeText = text === null || text === undefined ? "-" : text.toString();
      doc.fontSize(isHeader ? 10 : 9).text(safeText, x, y, { width: colWidths[i] || 50 });
      x += colWidths[i] || 50;
    });
  };

  let y = doc.y + 10;
  drawRow(headers, y, true);
  y += 20;

  (data.feedbacks || []).forEach(fb => {
    const row = [
      fb.orNumber || "-",
      fb.customerName || "-",
      fb.customerType || "-",
      fb.menuItems?.join("; ") || "-",
      fb.overallExperience || "-",
      fb.category || "-",
      fb.comment || "-",
      fb.date ? new Date(fb.date).toLocaleDateString() : "-"
    ];
    drawRow(row, y);
    y += 20;
    if (y > 700) { doc.addPage(); y = 30; }
  });


  doc.addPage();
  doc.fontSize(14).text("Section 3: Ratings Breakdown", { underline: true });
  const ratings = data.ratings || {};
  const ratingMetrics = [
    ["Overall Experience", ratings.overall || 0],
    ["Food Quality", ratings.food || 0],
    ["Ambiance", ratings.ambiance || 0],
    ["Service", ratings.service || 0],
    ["Value for Money", ratings.value || 0],
    ["Staff Attitude", ratings.staff || 0],
    ["Bartender Attitude", ratings.bartender || 0]
  ];

  let tableY = doc.y + 10;
  const tableX = 50;
  const cellHeight = 20;
  const col1Width = 150;
  const col2Width = 50;

  ratingMetrics.forEach(([aspect, score]) => {
    if (tableY > 700) { doc.addPage(); tableY = 30; }
    doc.rect(tableX, tableY, col1Width, cellHeight).stroke();
    doc.rect(tableX + col1Width, tableY, col2Width, cellHeight).stroke();
    doc.text(aspect, tableX + 5, tableY + 5);
    doc.text(score.toString(), tableX + col1Width + 5, tableY + 5);
    tableY += cellHeight;
  });

  ratingMetrics.forEach(([aspect, score], i) => {
    const barWidth = Math.max(0, Math.min(score / 5, 1)) * 200; // safe 0-5
    doc.rect(tableX + col1Width + col2Width + 20, 50 + i*25, barWidth, 10).fillColor("blue").fill();
  });


  doc.addPage();
  doc.fontSize(14).text("Section 4: Top Feedback Highlights", { underline: true });
  y = doc.y + 10;
  (data.feedbacks || []).slice(0, 10).forEach((fb, idx) => {
    doc.fontSize(12).text(`${idx + 1}. "${fb.comment || "-"}" - ${fb.customerName || "Anonymous"}`);
    y += 15;
    if (y > 700) { doc.addPage(); y = 30; }
  });


  doc.fontSize(10).text("Company Name | Address | Contact | Page 1 of 1", 30, 770, { align: "center" });

  return doc;
};
