import PDFDocument from "pdfkit";
import { ChartJSNodeCanvas } from "chartjs-node-canvas";

export const generateFeedbackReportPDF = async (feedbacks, reportTitle, generatedBy) => {
  const doc = new PDFDocument({ margin: 30, size: "A4" });

 
  doc.fontSize(16).text(reportTitle, { align: "center" });
  doc.moveDown(0.5);
  doc.fontSize(9).text(
    `Generated by: ${generatedBy} | Date: ${new Date().toLocaleDateString()}`,
    { align: "center" }
  );
  doc.moveDown(1);

  const chartCanvas = new ChartJSNodeCanvas({ width: 400, height: 250 });
  const ratingCounts = [1, 2, 3, 4, 5].map(
    (r) => feedbacks.filter((f) => f.overallExperience === r).length
  );
  const chartConfig = {
    type: "bar",
    data: {
      labels: ["1", "2", "3", "4", "5"],
      datasets: [
        {
          label: "Overall Experience",
          data: ratingCounts,
          backgroundColor: ["#f87171", "#fbbf24", "#a3e635", "#34d399", "#60a5fa"],
        },
      ],
    },
    options: {
      plugins: {
        legend: { display: false },
        title: { display: true, text: "Ratings Distribution", font: { size: 12 } },
      },
      scales: { y: { beginAtZero: true, ticks: { stepSize: 1 } } },
    },
  };
  const chartBuffer = await chartCanvas.renderToBuffer(chartConfig);
  doc.image(chartBuffer, { fit: [400, 250], align: "center", valign: "top" });
  doc.moveDown(1.5);


  const headers = ["OR", "Customer", "Type", "Menu", "Message", "Rating", "Date"];
  const colWidths = [30, 70, 50, 80, 120, 35, 45]; // smaller, flexible
  let y = doc.y;

  const drawRow = (row, y, isHeader = false) => {
    let x = 30;
    let rowHeight = 0;


    const cellHeights = row.map((text, i) => {
      const width = colWidths[i];
      const options = { width, align: "left" };
      const height = doc.heightOfString(String(text || "-"), options);
      return height;
    });
    rowHeight = Math.max(...cellHeights) + 4;

    row.forEach((text, i) => {
      doc.fontSize(isHeader ? 8 : 7).text(String(text || "-"), x, y, {
        width: colWidths[i],
        align: "left",
      });
      x += colWidths[i];
    });

    return rowHeight;
  };


  y += drawRow(headers, y, true) + 4;


  for (const fb of feedbacks) {
    const row = [
      fb.orNumber,
      fb.customerName || "-",
      fb.customerType || "-",
      fb.menuItems || "-",
      fb.message || "-",
      fb.overallExperience ?? "-",
      fb.createdAt ? new Date(fb.createdAt).toLocaleDateString() : "-",
    ];

    const rowHeight = drawRow(row, y);
    y += rowHeight;


    if (y > 750) {
      doc.addPage();
      y = 40;
      y += drawRow(headers, y, true) + 4;
    }
  }

  return doc;
};
