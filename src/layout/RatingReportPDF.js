import PDFDocument from "pdfkit";
import { ChartJSNodeCanvas } from "chartjs-node-canvas";

export const generateRatingReportPDF = async (ratings, reportTitle, generatedBy) => {
  const doc = new PDFDocument({ margin: 40, size: "A4" });

  doc.fontSize(18).text(reportTitle, { align: "center" });
  doc.fontSize(10).text(
    `Generated by: ${generatedBy} | Date: ${new Date().toLocaleDateString()}`,
    { align: "center" }
  );
  doc.moveDown(2);

  const chartWidth = 400;
  const chartHeight = 250;
  const chartJSNodeCanvas = new ChartJSNodeCanvas({ width: chartWidth, height: chartHeight, backgroundColour: "white" });

  const categories = ["Overall","Food","Service","Ambiance","Value","Staff","Bartender"];
  const averages = categories.map(cat => {
    const total = ratings.reduce((sum, r) => {
      switch(cat) {
        case "Overall": return sum + (r.overallExperience ?? 0);
        case "Food": return sum + (r.foodQuality ?? 0);
        case "Service": return sum + (r.service ?? 0);
        case "Ambiance": return sum + (r.ambiance ?? 0);
        case "Value": return sum + (r.valueForMoney ?? 0);
        case "Staff": return sum + (r.staffAttitude ?? 0);
        case "Bartender": return sum + (r.bartenderAttitude ?? 0);
        default: return sum;
      }
    }, 0);
    return ratings.length > 0 ? total / ratings.length : 0;
  });

  const chartConfig = {
    type: "line",
    data: {
      labels: categories,
      datasets: [{
        label: "Average Rating",
        data: averages,
        borderColor: "#2196F3",
        backgroundColor: "#60a5fa88",
        fill: true,
        tension: 0.3,
        pointBackgroundColor: "#1e40af",
        pointRadius: 5
      }]
    },
    options: {
      plugins: {
        legend: { display: true, position: "top" },
        title: { display: true, text: "Average Ratings per Category", font: { size: 14 } }
      },
      scales: { y: { beginAtZero: true, suggestedMax: 5 } }
    }
  };

  const chartBuffer = await chartJSNodeCanvas.renderToBuffer(chartConfig);
  const chartX = (doc.page.width - chartWidth) / 2;
  doc.image(chartBuffer, chartX, doc.y, { width: chartWidth, height: chartHeight });
  doc.moveDown(25);


  doc.fontSize(12).fillColor("#000").text("📊 Summary / Overview", { underline: true });
  categories.forEach((cat, i) => {
    doc.fontSize(10).text(`${cat}: ${averages[i].toFixed(2)}`, { indent: 10 });
  });
  doc.moveDown(1);


  const bestCategory = categories.reduce((a,b)=>averages[categories.indexOf(a)]>averages[categories.indexOf(b)]?a:b);
  const worstCategory = categories.reduce((a,b)=>averages[categories.indexOf(a)]<averages[categories.indexOf(b)]?a:b);

  const suggestions = {
    Food: "Consider enhancing flavor consistency and menu variety.",
    Service: "Focus on faster service and staff friendliness.",
    Ambiance: "Improve lighting, music, and seating comfort.",
    Value: "Offer more value combos or discounts.",
    Staff: "Provide additional training for staff interaction.",
    Bartender: "Ensure drinks are consistent and served quickly.",
    Overall: "Encourage overall improvement by focusing on weakest category."
  };

  doc.fontSize(12).fillColor("#000").text("💡 Suggestions / Insights", { underline: true });
  doc.moveDown(0.3);
  doc.fontSize(10).text(`🌟 Best Category: ${bestCategory} (Avg: ${averages[categories.indexOf(bestCategory)].toFixed(2)})`, { indent: 10 });
  if (averages[categories.indexOf(worstCategory)] < 4) {
    doc.fontSize(10).text(`⚠️ Needs Improvement: ${worstCategory} (Avg: ${averages[categories.indexOf(worstCategory)].toFixed(2)})`, { indent: 10 });
    doc.fontSize(10).fillColor("#555").text(`💡 Suggested Action: ${suggestions[worstCategory]}`, { indent: 20 });
  }
  doc.moveDown(2);


  const headers = ["Overall","Food","Service","Ambiance","Value","Staff","Bartender","Date"];
  const colWidths = [50,50,50,50,50,50,50,60];
  let y = doc.y;

  const drawRow = (row, yPos, isHeader = false) => {
    let x = doc.page.margins.left;
    row.forEach((text, i) => {
      doc.fontSize(isHeader ? 10 : 9)
         .fillColor("#000")
         .text(String(text ?? "-"), x, yPos, { width: colWidths[i], ellipsis: true });
      x += colWidths[i];
    });
  };

  drawRow(headers, y, true);
  y += 20;

  ratings.forEach(r => {
    const row = [
      r.overallExperience ?? "-",
      r.foodQuality ?? "-",
      r.service ?? "-",
      r.ambiance ?? "-",
      r.valueForMoney ?? "-",
      r.staffAttitude ?? "-",
      r.bartenderAttitude ?? "-",
      r.createdAt ? new Date(r.createdAt).toLocaleDateString() : "-"
    ];
    drawRow(row, y);
    y += 20;
    if (y > doc.page.height - 60) {
      doc.addPage();
      y = doc.page.margins.top;
      drawRow(headers, y, true);
      y += 20;
    }
  });

  return doc;
};
