import PDFDocument from "pdfkit";

export const generateSummaryReportPDF = (summaryData, reportTitle, generatedBy) => {
  const doc = new PDFDocument({ margin: 30, size: "A4" });
  doc.fontSize(18).text(reportTitle, { align: "center" });
  doc.fontSize(10).text(`Generated by: ${generatedBy} | Date: ${new Date().toLocaleDateString()}`, { align: "center" });
  doc.moveDown(2);

  let y = doc.y + 10;
  Object.entries(summaryData).forEach(([key, value]) => {
    doc.fontSize(12).text(`${key}: ${value ?? "-"}`);
    y += 20;
    if (y > 700) { doc.addPage(); y = 30; }
  });

  return doc;
};
